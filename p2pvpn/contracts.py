"""Small ports: domain services do not depend on Linux or asyncio transports."""
from typing import Protocol, Callable
from .models import Record


class Link(Protocol):
    def open(self, receive: Callable[[bytes], None], failed: Callable[[Exception], None]) -> None: ...
    def write(self, frame: bytes) -> None: ...
    def close(self) -> None: ...


class Transport(Protocol):
    async def open(self, receive: Callable[[bytes, tuple], None]) -> None: ...
    def send(self, packet: bytes, address: tuple) -> None: ...
    def close(self) -> None: ...


class Discovery(Protocol):
    async def start(self) -> None: ...
    async def publish(self, record: Record) -> bool: ...
    async def resolve(self, name: str) -> Record | None: ...
    def close(self) -> None: ...
